-- Promos: visitors see visible posters; admins see hidden ones too.
create policy "Visible promos are public" on public.promos
  for select to anon using (is_active);
create policy "Signed-in users see visible promos, admins see all" on public.promos
  for select to authenticated using (is_active or (select private.is_admin()));
create policy "Admins insert promos" on public.promos
  for insert to authenticated with check ((select private.is_admin()));
create policy "Admins update promos" on public.promos
  for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));
create policy "Admins delete promos" on public.promos
  for delete to authenticated using ((select private.is_admin()));

-- Lets the admin panel check whether the signed-in user is an admin.
create policy "Users can see their own admin row" on public.admins
  for select to authenticated using (user_id = (select auth.uid()));

-- ---------------------------------------------------------------- save item
-- Creates (p_item_id null) or replaces an item together with its modifier
-- groups/options in one transaction. Runs as the caller, so RLS applies.
create function public.save_menu_item(p_item jsonb, p_item_id bigint default null)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_id bigint;
  v_group jsonb;
  v_group_id bigint;
begin
  if not (select private.is_admin()) then
    raise exception 'Only admins can edit the menu' using errcode = '42501';
  end if;

  if p_item_id is null then
    insert into public.menu_items (
      category_id, name, name_pt, name_tet, description, description_pt, description_tet,
      price, image_url, is_available, display_order
    ) values (
      (p_item->>'category_id')::bigint,
      p_item->>'name', p_item->>'name_pt', p_item->>'name_tet',
      p_item->>'description', p_item->>'description_pt', p_item->>'description_tet',
      coalesce((p_item->>'price')::numeric, 0),
      p_item->>'image_url',
      coalesce((p_item->>'is_available')::boolean, true),
      coalesce((p_item->>'display_order')::integer, 0)
    )
    returning id into v_id;
  else
    update public.menu_items set
      category_id = (p_item->>'category_id')::bigint,
      name = p_item->>'name',
      name_pt = p_item->>'name_pt',
      name_tet = p_item->>'name_tet',
      description = p_item->>'description',
      description_pt = p_item->>'description_pt',
      description_tet = p_item->>'description_tet',
      price = coalesce((p_item->>'price')::numeric, 0),
      image_url = p_item->>'image_url',
      is_available = coalesce((p_item->>'is_available')::boolean, true),
      display_order = coalesce((p_item->>'display_order')::integer, 0)
    where id = p_item_id
    returning id into v_id;

    if v_id is null then
      raise exception 'Menu item % not found', p_item_id using errcode = 'P0002';
    end if;

    delete from public.modifier_groups where menu_item_id = v_id;
  end if;

  for v_group in
    select g from jsonb_array_elements(coalesce(p_item->'modifier_groups', '[]'::jsonb)) as t(g)
  loop
    insert into public.modifier_groups (menu_item_id, name, selection_type, required)
    values (
      v_id,
      v_group->>'name',
      coalesce(v_group->>'selection_type', 'single'),
      coalesce((v_group->>'required')::boolean, false)
    )
    returning id into v_group_id;

    insert into public.modifier_options (group_id, name, name_pt, name_tet, price_delta)
    select v_group_id, o->>'name', o->>'name_pt', o->>'name_tet', coalesce((o->>'price_delta')::numeric, 0)
    from jsonb_array_elements(coalesce(v_group->'options', '[]'::jsonb)) with ordinality as t(o, ord)
    order by ord;
  end loop;

  return v_id;
end;
$$;
revoke all on function public.save_menu_item(jsonb, bigint) from public, anon;
grant execute on function public.save_menu_item(jsonb, bigint) to authenticated;
