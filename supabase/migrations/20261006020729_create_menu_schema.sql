-- Helpers live in a schema the Data API does not expose.
create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated;

-- ---------------------------------------------------------------- tables
create table public.categories (
  id bigint generated by default as identity primary key,
  name varchar(120) not null check (length(trim(name)) > 0),
  name_pt varchar(120),
  name_tet varchar(120),
  display_order integer not null default 0
);

create table public.menu_items (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories (id) on delete cascade,
  name varchar(200) not null check (length(trim(name)) > 0),
  name_pt varchar(200),
  name_tet varchar(200),
  description text,
  description_pt text,
  description_tet text,
  price numeric(10, 2) not null default 0 check (price >= 0),
  image_url varchar(500),
  is_available boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index menu_items_category_id_idx on public.menu_items (category_id);

create table public.modifier_groups (
  id bigint generated by default as identity primary key,
  menu_item_id bigint not null references public.menu_items (id) on delete cascade,
  name varchar(120) not null check (length(trim(name)) > 0),
  selection_type varchar(20) not null default 'single' check (selection_type in ('single', 'multiple')),
  required boolean not null default false
);
create index modifier_groups_menu_item_id_idx on public.modifier_groups (menu_item_id);

create table public.modifier_options (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.modifier_groups (id) on delete cascade,
  name varchar(120) not null check (length(trim(name)) > 0),
  name_pt varchar(120),
  name_tet varchar(120),
  price_delta numeric(10, 2) not null default 0
);
create index modifier_options_group_id_idx on public.modifier_options (group_id);

create table public.promos (
  id bigint generated by default as identity primary key,
  image_url varchar(500) not null,
  caption text,
  display_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Who may edit. Rows are added by hand (SQL editor), never from the API.
create table public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------- helpers
create function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admins where user_id = (select auth.uid()));
$$;
revoke all on function private.is_admin() from public;
grant execute on function private.is_admin() to authenticated;

create function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger menu_items_set_updated_at
before update on public.menu_items
for each row execute function private.set_updated_at();

-- ---------------------------------------------------------------- grants
revoke all on public.categories, public.menu_items, public.modifier_groups,
  public.modifier_options, public.promos, public.admins from anon, authenticated;
grant select on public.categories, public.menu_items, public.modifier_groups,
  public.modifier_options, public.promos to anon, authenticated;
grant insert, update, delete on public.categories, public.menu_items, public.modifier_groups,
  public.modifier_options, public.promos to authenticated;
grant select on public.admins to authenticated;
revoke all on all sequences in schema public from anon;
grant usage, select on all sequences in schema public to authenticated;

-- ---------------------------------------------------------------- RLS
alter table public.categories enable row level security;
alter table public.menu_items enable row level security;
alter table public.modifier_groups enable row level security;
alter table public.modifier_options enable row level security;
alter table public.promos enable row level security;
alter table public.admins enable row level security;

-- Menu: everyone reads, only admins write.
create policy "Menu categories are public" on public.categories
  for select to anon, authenticated using (true);
create policy "Admins insert categories" on public.categories
  for insert to authenticated with check ((select private.is_admin()));
create policy "Admins update categories" on public.categories
  for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));
create policy "Admins delete categories" on public.categories
  for delete to authenticated using ((select private.is_admin()));

